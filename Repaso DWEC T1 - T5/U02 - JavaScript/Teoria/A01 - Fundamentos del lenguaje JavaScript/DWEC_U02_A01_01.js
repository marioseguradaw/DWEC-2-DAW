// 1.3. Operadores: aclaraciones
console.log('1' + 2); // "12"
console.log(2 + '1'); // "21"

/* Conversión a número */
console.log(6 - '2'); // 4
console.log('4' / '2'); // 2

/* Modificaciones sobre la misma variable */
let a = 5;
a += 5; // Es lo mismo que (a = a + 5)
a /= 3; // Es lo mismo que (a = a / 3)